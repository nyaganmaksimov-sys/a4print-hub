const originalFetch=globalThis.fetch;
const stateKey=Symbol.for('a4print.moysklad.request.queue');
const queueState=globalThis[stateKey]||(globalThis[stateKey]={tail:Promise.resolve(),lastStarted:0});
const MIN_GAP_MS=100;
const MAX_RATE_RETRIES=4;

const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));

function toTime(value){
  const s=String(value||'').trim();
  if(!s)return NaN;
  const d=new Date(s.replace(' ','T'));
  return d.getTime();
}

function sanitizeShift(shift){
  if(!shift||typeof shift!=='object')return shift;
  const open=toTime(shift.openDate||shift.moment||shift.created);
  const close=toTime(shift.closeDate);
  if(Number.isFinite(open)&&Number.isFinite(close)&&close<open){
    shift={...shift,closeDate:null};
  }
  return shift;
}

function moscowNow(){
  const parts=new Intl.DateTimeFormat('sv-SE',{
    timeZone:'Europe/Moscow',year:'numeric',month:'2-digit',day:'2-digit',
    hour:'2-digit',minute:'2-digit',second:'2-digit',hourCycle:'h23'
  }).format(new Date());
  return parts.replace('T',' ');
}

function isMoySkladUrl(url){
  try{return new URL(url).hostname==='api.moysklad.ru'}catch{return false}
}

function isRetailShiftUrl(url){
  try{
    const u=new URL(url);
    return u.hostname==='api.moysklad.ru'&&u.pathname.includes('/entity/retailshift');
  }catch{return false}
}

function requestUrl(input){
  return typeof input==='string'||input instanceof URL?String(input):String(input?.url||'');
}

function requestMethod(input,init={}){
  return String(init?.method||input?.method||'GET').toUpperCase();
}

function retryAfterMs(response,attempt){
  const raw=String(response?.headers?.get?.('retry-after')||'').trim();
  const seconds=Number(raw);
  if(Number.isFinite(seconds)&&seconds>0)return Math.min(10000,seconds*1000);
  const date=Date.parse(raw);
  if(Number.isFinite(date))return Math.min(10000,Math.max(0,date-Date.now()));
  return Math.min(5000,550*(2**attempt));
}

async function queuedMoySkladFetch(input,options){
  const run=async()=>{
    const wait=Math.max(0,queueState.lastStarted+MIN_GAP_MS-Date.now());
    if(wait)await sleep(wait);

    let response;
    for(let attempt=0;attempt<MAX_RATE_RETRIES;attempt++){
      queueState.lastStarted=Date.now();
      response=await originalFetch(input,options);
      if(response.status!==429)return response;
      if(attempt>=MAX_RATE_RETRIES-1)return response;
      await sleep(retryAfterMs(response,attempt));
    }
    return response;
  };

  const task=queueState.tail.then(run,run);
  queueState.tail=task.then(()=>undefined,()=>undefined);
  return task;
}

async function duplicateNameConflict(response){
  if(response?.status!==412)return false;
  try{
    const text=await response.clone().text();
    return /(?:"code"\s*:\s*3006|code\D+3006)/i.test(text)&&/(?:"parameter"\s*:\s*"name"|уникальност[^\n]*name)/i.test(text);
  }catch{return false}
}

function uniqueShiftName(url){
  let id='shift';
  try{id=new URL(url).pathname.split('/').filter(Boolean).pop()||id}catch{}
  const stamp=moscowNow().replace(/\D/g,'').slice(0,14);
  return `A4PRINT-${stamp}-${String(id).slice(0,12)}`;
}

globalThis.fetch=async function patchedMoySkladFetch(input,init={}){
  const url=requestUrl(input);
  if(!isMoySkladUrl(url))return originalFetch(input,init);

  let options=init||{};
  const method=requestMethod(input,options);

  if(isRetailShiftUrl(url)&&method==='PUT'&&typeof options.body==='string'){
    try{
      const body=JSON.parse(options.body);
      if(body&&Object.prototype.hasOwnProperty.call(body,'closeDate')&&body.closeDate){
        body.closeDate=moscowNow();
        options={...options,body:JSON.stringify(body)};
      }
    }catch{}
  }

  let response=await queuedMoySkladFetch(input,options);

  // Legacy/duplicated retail shifts can exist with the same autogenerated name.
  // MoySklad validates name uniqueness again on PUT and returns 412/3006 even
  // when HUB only changes closeDate. Repair only that specific legacy conflict.
  if(isRetailShiftUrl(url)&&method==='PUT'&&typeof options.body==='string'&&await duplicateNameConflict(response)){
    try{
      const body=JSON.parse(options.body);
      if(body&&body.closeDate){
        body.name=uniqueShiftName(url);
        await sleep(MIN_GAP_MS);
        response=await queuedMoySkladFetch(input,{...options,body:JSON.stringify(body)});
        if(response.ok)console.warn(`[MoySklad shift] duplicate name repaired: ${body.name}`);
      }
    }catch{}
  }

  if(!isRetailShiftUrl(url)||method!=='GET'||!response.ok)return response;

  try{
    const data=await response.clone().json();
    if(Array.isArray(data?.rows))data.rows=data.rows.map(sanitizeShift);
    else if(data&&typeof data==='object')Object.assign(data,sanitizeShift(data));
    const headers=new Headers(response.headers);
    headers.delete('content-length');
    headers.delete('content-encoding');
    return new Response(JSON.stringify(data),{status:response.status,statusText:response.statusText,headers});
  }catch{
    return response;
  }
};
